"""PDF invoice rendering with ReportLab."""

from __future__ import annotations

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from .models import Invoice
from .totals import format_money, invoice_totals


def _header_styles() -> tuple:
    styles = getSampleStyleSheet()
    title = styles["Title"]
    normal = styles["Normal"]
    return title, normal


def build_story(invoice: Invoice) -> list:
    """Build the flowable list (story) for the invoice PDF."""
    title, normal = _header_styles()
    totals = invoice_totals(invoice)

    story: list = []
    story.append(Paragraph("INVOICE", title))
    story.append(Spacer(1, 0.25 * inch))

    # Business / from block
    story.append(Paragraph("<b>Asdale Dynamics, LLC</b>", normal))
    story.append(Paragraph("Indiana, USA", normal))
    story.append(Paragraph("dylanasdale.github.io", normal))
    story.append(Spacer(1, 0.3 * inch))

    # Invoice meta + client side by side
    meta_rows = [
        [
            Paragraph("<b>Invoice #:</b>", normal),
            Paragraph(invoice.invoice_number, normal),
        ],
        [Paragraph("<b>Date:</b>", normal), Paragraph(invoice.invoice_date, normal)],
        [Paragraph("<b>Client:</b>", normal), Paragraph(invoice.client.name, normal)],
    ]
    if invoice.client.email:
        meta_rows.append(
            [
                Paragraph("<b>Email:</b>", normal),
                Paragraph(invoice.client.email, normal),
            ]
        )
    if invoice.client.address:
        meta_rows.append(
            [
                Paragraph("<b>Address:</b>", normal),
                Paragraph(invoice.client.address, normal),
            ]
        )
    meta_table = Table(meta_rows, colWidths=[1.0 * inch, 4.5 * inch])
    meta_table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    story.append(meta_table)
    story.append(Spacer(1, 0.3 * inch))

    # Line items table
    data = [
        [
            Paragraph("<b>Description</b>", normal),
            Paragraph("<b>Qty</b>", normal),
            Paragraph("<b>Unit Price</b>", normal),
            Paragraph("<b>Total</b>", normal),
        ]
    ]
    for item in invoice.items:
        data.append(
            [
                Paragraph(item.description, normal),
                Paragraph(f"{item.quantity:g}", normal),
                Paragraph(format_money(item.unit_price), normal),
                Paragraph(format_money(item.line_total()), normal),
            ]
        )
    data.append(
        [
            Paragraph("", normal),
            Paragraph("", normal),
            Paragraph("<b>Subtotal</b>", normal),
            Paragraph(f"<b>{format_money(totals['subtotal'])}</b>", normal),
        ]
    )
    data.append(
        [
            Paragraph("", normal),
            Paragraph("", normal),
            Paragraph(f"<b>Tax ({invoice.tax_rate:.0%})</b>", normal),
            Paragraph(f"<b>{format_money(totals['tax'])}</b>", normal),
        ]
    )
    data.append(
        [
            Paragraph("", normal),
            Paragraph("", normal),
            Paragraph("<b>Total</b>", normal),
            Paragraph(f"<b>{format_money(totals['total'])}</b>", normal),
        ]
    )

    items_table = Table(
        data, colWidths=[3.2 * inch, 0.7 * inch, 1.1 * inch, 1.1 * inch]
    )
    items_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2f7")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#c9cfd8")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
                ("ALIGN", (0, 0), (0, -1), "LEFT"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LINEABOVE", (0, len(data) - 1), (-1, len(data) - 1), 1, colors.black),
                (
                    "BACKGROUND",
                    (0, len(data) - 1),
                    (-1, len(data) - 1),
                    colors.HexColor("#f4f6f9"),
                ),
            ]
        )
    )
    story.append(items_table)
    story.append(Spacer(1, 0.4 * inch))

    story.append(
        Paragraph(
            "Thank you for your business. Generated by the Asdale Dynamics invoice generator "
            "(local-first, open source).",
            normal,
        )
    )
    return story


def render_pdf(invoice: Invoice, output_path: str) -> str:
    """Render ``invoice`` to a PDF at ``output_path``. Returns the path written."""
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        leftMargin=0.8 * inch,
        rightMargin=0.8 * inch,
        topMargin=0.8 * inch,
        bottomMargin=0.8 * inch,
        title=f"Invoice {invoice.invoice_number}",
        author="Asdale Dynamics, LLC",
    )
    doc.build(build_story(invoice))
    return output_path


def generate_pdf(invoice: Invoice, output_path: str | None = None) -> str:
    """Convenience: render invoice to PDF, defaulting to ``invoice-{number}.pdf``."""
    if output_path is None:
        output_path = f"invoice-{invoice.invoice_number}.pdf"
    return render_pdf(invoice, output_path)
